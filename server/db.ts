function ensureStorageDir() {
  if (!fs.existsSync(DATA_DIR)) {
    fs.mkdirSync(DATA_DIR, { recursive: true });
  }
}

export function readWorkspace(): WorkspaceData {
  ensureStorageDir();
  if (!fs.existsSync(DB_FILE)) {
    const seed = createSeedWorkspace();
    writeWorkspace(seed);
    return seed;
  }
  const raw = fs.readFileSync(DB_FILE, 'utf-8');
  return JSON.parse(raw) as WorkspaceData;
}

export function writeWorkspace(data: WorkspaceData): WorkspaceData {
  ensureStorageDir();
  const nextData: WorkspaceData = {
    ...data,
    lastUpdatedAt: new Date().toISOString(),
  };
  const tmpFile = `${DB_FILE}.tmp`;
  fs.writeFileSync(tmpFile, JSON.stringify(nextData, null, 2), 'utf-8');
  fs.renameSync(tmpFile, DB_FILE);
  return nextData;
}

export function getStorageFilePath(): string {
  return DB_FILE;
}
